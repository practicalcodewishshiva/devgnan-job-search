#!/usr/bin/env bash
# Business stack manager — runs the self-hosted apps from "15 GitHub repos to automate
# your business" with Docker Compose, one isolated project per app.
#
#   ./stack.sh init                 create stack.env + per-app secrets/.env files
#   ./stack.sh up [app...]          start apps (default: all)
#   ./stack.sh down [app...]        stop apps (data volumes are kept)
#   ./stack.sh status               show containers and URLs
#   ./stack.sh logs <app>           follow logs
#   ./stack.sh update [app...]      pull newer images and restart
#   ./stack.sh urls                 print the URL of every app
#
# Apps: n8n twenty calcom documenso chatwoot postiz invoiceninja plane
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APPS_DIR="$ROOT/apps"
ALL_APPS=(n8n twenty calcom documenso chatwoot postiz invoiceninja plane)

die() { echo "error: $*" >&2; exit 1; }
info() { echo "==> $*"; }

rand_hex() { openssl rand -hex "${1:-32}"; }
rand_pw() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-32}"; }

need() { command -v "$1" >/dev/null 2>&1 || die "'$1' is required (see README.md → Prerequisites)"; }

check_prereqs() {
  need docker
  need openssl
  docker compose version >/dev/null 2>&1 || die "Docker Compose v2 plugin is required ('docker compose')"
  docker info >/dev/null 2>&1 || die "Docker daemon is not running (or you lack permission: add yourself to the 'docker' group)"
}

load_stack_env() {
  [[ -f "$ROOT/stack.env" ]] || { cp "$ROOT/stack.env.example" "$ROOT/stack.env"; info "Created stack.env from stack.env.example — edit it, then re-run init."; }
  set -a; # shellcheck disable=SC1091
  source "$ROOT/stack.env"; set +a
}

# URL of an app: explicit <APP>_URL from stack.env, else scheme://host:port
app_url() {
  local upper="${1^^}" url_var port_var
  url_var="${upper}_URL"; port_var="${upper}_PORT"
  if [[ -n "${!url_var:-}" ]]; then echo "${!url_var}"; else echo "${PUBLIC_SCHEME}://${PUBLIC_HOST}:${!port_var}"; fi
}

# Secrets are generated once per app and never overwritten (changing them would lock you
# out of encrypted data). They live in apps/<app>/secrets.env, which is git-ignored.
gen_secrets() {
  local app="$1" f="$APPS_DIR/$1/secrets.env"
  [[ -f "$f" ]] && return 0
  umask 077
  case "$app" in
    n8n)          printf 'DB_PASSWORD=%s\nN8N_ENCRYPTION_KEY=%s\n' "$(rand_pw)" "$(rand_hex)" ;;
    twenty)       printf 'DB_PASSWORD=%s\nAPP_SECRET=%s\n' "$(rand_pw)" "$(rand_hex)" ;;
    calcom)       printf 'DB_PASSWORD=%s\nNEXTAUTH_SECRET=%s\nCALENDSO_ENCRYPTION_KEY=%s\n' "$(rand_pw)" "$(rand_hex)" "$(rand_hex 16)" ;;
    documenso)    printf 'DB_PASSWORD=%s\nNEXTAUTH_SECRET=%s\nENCRYPTION_KEY=%s\nENCRYPTION_SECONDARY_KEY=%s\nSIGNING_PASSPHRASE=%s\n' \
                    "$(rand_pw)" "$(rand_hex)" "$(rand_hex)" "$(rand_hex)" "$(rand_pw 24)" ;;
    chatwoot)     printf 'DB_PASSWORD=%s\nREDIS_PASSWORD=%s\nSECRET_KEY_BASE=%s\n' "$(rand_pw)" "$(rand_pw)" "$(rand_hex 64)" ;;
    postiz)       printf 'DB_PASSWORD=%s\nTEMPORAL_DB_PASSWORD=%s\nJWT_SECRET=%s\n' "$(rand_pw)" "$(rand_pw)" "$(rand_hex)" ;;
    invoiceninja) printf 'DB_PASSWORD=%s\nDB_ROOT_PASSWORD=%s\nAPP_KEY=base64:%s\nADMIN_PASSWORD=%s\n' \
                    "$(rand_pw)" "$(rand_pw)" "$(openssl rand -base64 32)" "$(rand_pw 20)" ;;
    plane)        printf 'POSTGRES_PASSWORD=%s\nRABBITMQ_PASSWORD=%s\nSECRET_KEY=%s\nLIVE_SERVER_SECRET_KEY=%s\nAWS_ACCESS_KEY_ID=%s\nAWS_SECRET_ACCESS_KEY=%s\n' \
                    "$(rand_pw)" "$(rand_pw)" "$(rand_hex)" "$(rand_hex)" "$(rand_hex 10)" "$(rand_pw 40)" ;;
  esac >"$f"
  info "$app: generated secrets → apps/$app/secrets.env"
}

# Self-signed certificate Documenso uses to seal signed PDFs.
documenso_cert() {
  local d="$APPS_DIR/documenso"
  [[ -f "$d/cert.p12" ]] && return 0
  # shellcheck disable=SC1091
  local pass; pass="$(. "$d/secrets.env"; echo "$SIGNING_PASSPHRASE")"
  local tmp; tmp="$(mktemp -d)"
  openssl req -x509 -newkey rsa:2048 -nodes -days 3650 -subj "/CN=${PUBLIC_HOST} Documenso" \
    -keyout "$tmp/key.pem" -out "$tmp/cert.pem" 2>/dev/null
  openssl pkcs12 -export -out "$d/cert.p12" -inkey "$tmp/key.pem" -in "$tmp/cert.pem" \
    -passout "pass:$pass" -certpbe AES-256-CBC -keypbe AES-256-CBC -macalg sha256 2>/dev/null
  rm -rf "$tmp"
  chmod 644 "$d/cert.p12"   # the container runs as a non-root user and must read it
  info "documenso: generated self-signed signing certificate → apps/documenso/cert.p12"
}

# apps/<app>/.env = global settings + this app's URL + its secrets + optional extra.env
# (extra.env is where you put per-app API keys, e.g. Postiz social logins). Rebuilt on
# every init/up so stack.env edits are picked up.
write_env() {
  local app="$1" d="$APPS_DIR/$1" url
  url="$(app_url "$app")"
  {
    echo "# GENERATED by stack.sh — edit stack.env / apps/$app/extra.env instead"
    grep -Ev '^\s*(#|$)' "$ROOT/stack.env"
    echo "${app^^}_URL=$url"
    if [[ "$app" == plane ]]; then
      grep -Ev '^\s*(#|$)' "$d/plane.env.example"
      local host; host="$(sed -E 's#^[a-z]+://##; s#[:/].*$##' <<<"$url")"
      echo "APP_DOMAIN=$host"
      echo "WEB_URL=$url"
      echo "CORS_ALLOWED_ORIGINS=$url"
      echo "LISTEN_HTTP_PORT=$PLANE_PORT"
      echo "LISTEN_HTTPS_PORT=${PLANE_HTTPS_PORT:-8443}"
    fi
    cat "$d/secrets.env"
    if [[ "$app" == plane ]]; then
      # shellcheck disable=SC1091
      ( . "$d/secrets.env"
        echo "DATABASE_URL=postgresql://plane:${POSTGRES_PASSWORD}@plane-db/plane"
        echo "AMQP_URL=amqp://plane:${RABBITMQ_PASSWORD}@plane-mq:5672/plane" )
    fi
    [[ -f "$d/extra.env" ]] && cat "$d/extra.env"
  } >"$d/.env"
  chmod 600 "$d/.env"
}

prepare() {
  local app="$1"
  [[ -d "$APPS_DIR/$app" ]] || die "unknown app '$app' (choose from: ${ALL_APPS[*]})"
  gen_secrets "$app"
  [[ "$app" == documenso ]] && documenso_cert
  write_env "$app"
}

compose() { local app="$1"; shift; docker compose --project-directory "$APPS_DIR/$app" -f "$APPS_DIR/$app/docker-compose.yml" "$@"; }

apps_or_all() { if [[ $# -gt 0 ]]; then echo "$@"; else echo "${ALL_APPS[@]}"; fi; }

print_urls() {
  for app in "${ALL_APPS[@]}"; do printf '  %-13s %s\n' "$app" "$(app_url "$app")"; done
}

cmd="${1:-help}"; shift || true
case "$cmd" in
  init)
    need openssl; load_stack_env
    for app in $(apps_or_all "$@"); do prepare "$app"; done
    info "Ready. Start everything with: ./stack.sh up   (or one app: ./stack.sh up n8n)"
    ;;
  up)
    check_prereqs; load_stack_env
    for app in $(apps_or_all "$@"); do
      prepare "$app"; info "starting $app"; compose "$app" up -d
    done
    echo; info "URLs (first boot can take a few minutes while databases migrate):"; print_urls
    ;;
  down)
    check_prereqs; load_stack_env
    for app in $(apps_or_all "$@"); do [[ -f "$APPS_DIR/$app/.env" ]] && { info "stopping $app"; compose "$app" down; }; done
    ;;
  update)
    check_prereqs; load_stack_env
    for app in $(apps_or_all "$@"); do prepare "$app"; info "updating $app"; compose "$app" pull; compose "$app" up -d; done
    ;;
  status)
    check_prereqs; load_stack_env
    for app in "${ALL_APPS[@]}"; do
      [[ -f "$APPS_DIR/$app/.env" ]] || continue
      echo "── $app  $(app_url "$app")"; compose "$app" ps --format 'table {{.Service}}\t{{.Status}}'
    done
    ;;
  logs)
    [[ $# -ge 1 ]] || die "usage: ./stack.sh logs <app>"
    check_prereqs; compose "$1" logs -f --tail=200 "${@:2}"
    ;;
  urls) load_stack_env; print_urls ;;
  help|-h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//' ;;
  *) die "unknown command '$cmd' (try ./stack.sh help)" ;;
esac
